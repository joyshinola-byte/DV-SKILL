df['date'] = pd.to_datetime(df['date'])


df['Sale Year'] = df['date'].dt.year


df['Property Age'] = df['Sale Year'] - df['yr_built']


df['Is Renovated'] = (df['yr_renovated'] > 0).astype(int)

df['Price_per_Sqft'] = df['price'] / df['sqft_living']

print(df[['price', 'sqft_living', 'Price_per_Sqft']].head(10))

df[['Price_per_Sqft']].head(10).plot(
    kind='bar', figsize=(8, 4), legend=False
)

plt.title('Price per Square Foot')
plt.xlabel('Property')
plt.ylabel('Price per Sqft')
plt.show()

Q1 = df['price'].quantile(0.25)
Q3 = df['price'].quantile(0.75)
IQR = Q3 - Q1

lower = Q1 - 1.5 * IQR
upper = Q3 + 1.5 * IQR

outliers = df[(df['price'] < lower) | (df['price'] > upper)]

print("Number of Outliers:", len(outliers))
print(outliers[['price']].head(10))

plt.figure(figsize=(8, 5))
sns.boxplot(y=df['price'])
plt.title('Outlier Analysis of Property Prices')
plt.ylabel('Price')
plt.show()

