import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('/content/drive/MyDrive/DV SKILL /kc_house_data.csv')

df.head()

df.tail()

df.shape

df.isnull().sum()

plt.figure(figsize=(10, 6))

sns.regplot(
    data=df,
    x='sqft_living',
    y='price',
    scatter_kws={'alpha': 0.3},
    line_kws={'color': 'black'}
)

plt.title('Living Area vs House Price')
plt.xlabel('Living Area (Square Feet)')
plt.ylabel('House Price ($)')
plt.tight_layout()
plt.show()

plt.figure(figsize=(12, 6))

sns.boxplot(data=df, x='grade', y='price')

plt.title('House Price Distribution by Property Grade')
plt.xlabel('Property Grade')
plt.ylabel('House Price ($)')
plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 6))

sns.boxplot(data=df, x='waterfront', y='price')

plt.title('House Price Distribution by Waterfront Status')
plt.xlabel('Waterfront (0 = No, 1 = Yes)')
plt.ylabel('House Price ($)')
plt.xticks([0, 1], ['No Waterfront', 'Waterfront'])
plt.tight_layout()
plt.show()

plt.figure(figsize=(12, 8))

scatter = plt.scatter(
    df['long'],
    df['lat'],
    c=df['price'],
    cmap='coolwarm',
    s=12,
    alpha=0.6
)

plt.colorbar(scatter, label='House Price ($)')
plt.title('Geographic House Price Heatmap')
plt.xlabel('Longitude')
plt.ylabel('Latitude')
plt.tight_layout()
plt.show()

print("Real Estate Investment Summary Report")
print(df.groupby('zipcode')['price'].median().nlargest(5))